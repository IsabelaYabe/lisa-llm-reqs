def _collect_research_objects(base_dir: Path) -> list:
    """
    Loads research objects generated by the orchestrator (papers_test folder).
    Looks in papers_test/ieee and papers_test/acm. If not found, returns an empty list.
    """
    store = Storage()
    researches = []

    ieee_dir = base_dir / "ieee"
    if ieee_dir.exists():
        researches.extend(store.load_dir(ieee_dir, pattern="*.pkl", recursive=True))

    acm_dir = base_dir / "acm"
    if acm_dir.exists():
        researches.extend(store.load_dir(acm_dir, pattern="*.pkl", recursive=True))

    return researches


@pytest.fixture(scope="module")
def researches():
    """
    Uses the files already generated by test_papers_lab.py (default: papers_test/).
    If nothing is found, skips the tests.
    """
    base = Path("papers_test")
